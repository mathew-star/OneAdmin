"""``oneadmin init``: write a starting ``admin.py`` for a project's models.

The generated file uses the same suggestions as ``AdminSite.register_all``
(``oneadmin.core.autoconfig``), written out as ordinary, typed ``ModelAdmin`` classes so they
can be read, edited and reviewed. Nothing is generated at runtime; the file is the source of
truth from then on.
"""

from __future__ import annotations

import importlib
import json
import keyword
from collections.abc import Iterable, Sequence
from pathlib import Path
from types import ModuleType
from typing import Any

from sqlalchemy import inspect as sa_inspect
from sqlalchemy.ext.asyncio import async_sessionmaker
from sqlalchemy.orm import Mapper, configure_mappers

from oneadmin.core.autoconfig import Suggestion, suggest
from oneadmin.core.errors import ConfigurationError

LINE = 100
_HEADER = '''"""The admin panel, generated by `oneadmin init`. Edit it freely: it is yours now.

Next steps:
1. Mount it in your FastAPI app:          admin.mount(app, path="/admin")
2. Tell the CLI where it is (pyproject):  [tool.oneadmin] app = "{module}:admin"
3. Create OneAdmin's tables and a user:   oneadmin migrate && oneadmin createsuperuser
   (or set ONEADMIN_DEV=1 locally: tables are created and the first user is set up
   from the login page)

`oneadmin explain <model>` shows how each setting is resolved.
"""'''


def mapped_classes(module: ModuleType, attribute: str | None) -> list[type[Any]]:
    """Models from ``module:Base`` (every class of that base) or every mapped class that
    ``module`` defines or re-exports."""
    configure_mappers()
    if attribute:
        base = getattr(module, attribute, None)
        registry = getattr(base, "registry", None)
        if registry is None:
            raise ConfigurationError(f"{module.__name__}:{attribute} is not a declarative base")
        classes = [m.class_ for m in registry.mappers]
    else:
        classes = [
            value
            for value in vars(module).values()
            if isinstance(value, type) and _is_mapped(value)
        ]
    # Single-table inheritance subclasses share their parent's table: one admin per table.
    classes = [c for c in classes if not _shares_parent_table(c)]
    if not classes:
        raise ConfigurationError(
            f"No mapped models found in {module.__name__}"
            + (f":{attribute}" if attribute else "")
            + ". Point --models at the module (or package) that imports your models, "
            "or at module:Base."
        )
    return sorted(set(classes), key=lambda c: c.__name__)


def render(
    models: Sequence[type[Any]],
    *,
    models_module: ModuleType,
    admin_module: str,
    session: str,
    title: str,
) -> str:
    suggestions = [suggest(m) for m in models]
    lines = [_HEADER.format(module=admin_module), "", "from __future__ import annotations", ""]
    lines += ["import os", ""]
    lines += ["from oneadmin import AdminSite, ModelAdmin"]
    has_email = any(_has_email(m) for m in models)
    if has_email:
        lines += [
            "from oneadmin import conventions as cv",
            "from oneadmin.fields import EmailField",
        ]
    lines.append("")
    module, _, name = session.partition(":")
    if not module or not name:
        raise ConfigurationError("--session must look like 'app.database:async_session_maker'")
    lines.append(f"from {module} import {name} as session_factory")
    for module, names in _imports(models, models_module):
        lines += _wrap(f"from {module} import ", names, "")
    lines.append("")
    lines += [
        "admin = AdminSite(",
        f"    title={_q(title)},",
        "    session_factory=session_factory,",
        '    secret_key=os.environ.get("ONEADMIN_SECRET_KEY"),  # >= 32 random characters',
    ]
    if has_email:
        lines += [
            "    conventions=[",
            '        cv.field_type(EmailField(), r"(.*_)?email"),  # validated, shown as mailto links',
            "    ],",
        ]
    lines.append(")")
    for s in suggestions:
        lines += ["", "", *_admin_class(s)]  # two blank lines between top-level blocks
    return "\n".join(lines).rstrip() + "\n"


_SESSION_MODULES = ("database", "db", "core.database", "core.db", "db.session", "session", "deps")


def find_session_factory(root_package: str) -> str | None:
    """``module:name`` of an ``async_sessionmaker`` in the usual places of the project."""
    for suffix in _SESSION_MODULES:
        name = f"{root_package}.{suffix}"
        try:
            module = importlib.import_module(name)
        except ImportError:
            continue
        for attr, value in vars(module).items():
            if isinstance(value, async_sessionmaker) and not attr.startswith("_"):
                return f"{name}:{attr}"
    return None


def default_output(models_module: ModuleType) -> tuple[Path, str]:
    """``admin.py`` beside the models (``app/models.py`` or ``app/models/`` -> ``app/admin.py``)
    and the module path it will have (``app.admin``)."""
    file = Path(models_module.__file__ or "models.py")
    directory = file.parent.parent if file.name == "__init__.py" else file.parent
    parent, _, _ = models_module.__name__.rpartition(".")
    return directory / "admin.py", f"{parent}.admin" if parent else "admin"


def write(path: Path, source: str, *, force: bool) -> None:
    if path.exists() and not force:
        raise ConfigurationError(f"{path} already exists. Pass --force to overwrite it.")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(source, encoding="utf-8")


# ---- rendering helpers ---------------------------------------------------------------------
def _admin_class(s: Suggestion) -> list[str]:
    model = s.model.__name__
    lines = [f"@admin.register({model})", f"class {model}Admin(ModelAdmin[{model}]):"]
    body: list[str] = []
    body += _option("list_display", [_attr(model, n) for n in s.list_display])
    if s.search_fields:
        body += _option(
            "search_fields",
            [_q(n) if n.startswith(("^", "=")) else _attr(model, n) for n in s.search_fields],
        )
    if s.list_filter:
        body += _option("list_filter", [_attr(model, n) for n in s.list_filter])
    body += _option(
        "ordering",
        [
            f"{_attr(model, n[1:])}.desc()" if n.startswith("-") else _attr(model, n)
            for n in s.ordering
        ],
    )
    return lines + body


def _option(name: str, items: list[str]) -> list[str]:
    return _wrap(f"    {name} = (", items, ")", trailing_comma_single=True)


def _wrap(
    prefix: str, items: Iterable[str], suffix: str, *, trailing_comma_single: bool = False
) -> list[str]:
    items = list(items)
    inner = ", ".join(items) + ("," if trailing_comma_single and len(items) == 1 else "")
    one_line = f"{prefix}{inner}{suffix}"
    if len(one_line) <= LINE:
        return [one_line]
    indent = " " * (len(prefix) - len(prefix.lstrip()) + 4)
    opener = prefix if prefix.rstrip().endswith("(") else f"{prefix}("
    closer = suffix if suffix else ")"
    return [opener.rstrip(), *(f"{indent}{item}," for item in items), f"{indent[:-4]}{closer}"]


def _attr(model: str, name: str) -> str:
    return f"{model}.{name}" if name.isidentifier() and not keyword.iskeyword(name) else _q(name)


def _q(text: str) -> str:
    """A double-quoted Python string literal (the house style of ruff/black)."""
    return json.dumps(text)


def _imports(models: Sequence[type[Any]], models_module: ModuleType) -> list[tuple[str, list[str]]]:
    by_module: dict[str, list[str]] = {}
    for m in models:
        exported = getattr(models_module, m.__name__, None) is m
        module = models_module.__name__ if exported else m.__module__
        by_module.setdefault(module, []).append(m.__name__)
    return [(mod, sorted(names)) for mod, names in sorted(by_module.items())]


def _has_email(model: type[Any]) -> bool:
    mapper: Mapper[Any] = sa_inspect(model)
    return any(p.key == "email" or p.key.endswith("_email") for p in mapper.column_attrs)


def _is_mapped(cls: type[Any]) -> bool:
    return isinstance(sa_inspect(cls, raiseerr=False), Mapper)


def _shares_parent_table(cls: type[Any]) -> bool:
    mapper: Mapper[Any] = sa_inspect(cls)
    return mapper.inherits is not None and mapper.local_table is mapper.inherits.local_table
